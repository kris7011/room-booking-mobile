// Mirrors CurrentUserResponse in the .NET API
// (src/MeetingRoomBooking.Api/Features/Users/CurrentUserEndpoints.cs):
// who the API says the caller is, taken from the access token after it has
// validated its signature, issuer, audience and scope.
export interface CurrentUserResponse {
  displayName: string;
  /** preferred_username, usually an e-mail address. Display only, never a key. */
  username: string | null;
  tenantId: string;
  /** The API's own user record, or null until this identity has been registered. */
  user: RegisteredUser | null;
}

/** The API's own user: created by POST /api/me/registration, keyed by the token's issuer and object ID. */
export interface RegisteredUser {
  /** Generated by the API. An operator uses it to name the first Owner of the legacy organisation. */
  publicId: string;
  displayName: string;
  /** Empty for a new user: registration grants no organisation access. */
  organizations: OrganizationMembership[];
}

export type MembershipRole = 'Owner' | 'Admin' | 'Member';

export interface OrganizationMembership {
  publicId: string;
  name: string;
  /** The organisation that holds every room and booking from before organisations existed. */
  isLegacy: boolean;
  role: MembershipRole;
}

/** POST /api/me/registration: created is true only for the request that created the user. */
export interface RegistrationResponse {
  created: boolean;
  currentUser: CurrentUserResponse;
}
